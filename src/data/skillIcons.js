export const skillIconGroups = skillIconOptions.reduce((groups, icon) => {
  const group = groups.find((item) => item.label === icon.group);

  if (group) {
    group.options.push(icon);
  } else {
    groups.push({ label: icon.group, options: [icon] });
  }

  return groups;
}, []);

