export function getSkillIcon(iconKey) {
  return skillIconOptions.find((icon) => icon.value === iconKey)?.component || LuCode;
}

export function getSkillIconColor(iconKey) {
  const option = skillIconOptions.find((icon) => icon.value === iconKey);
  return iconColors[iconKey] || groupColors[option?.group] || groupColors.General;
}
